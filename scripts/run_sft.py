#!/usr/bin/env python3
"""
Causal-Masked Agent Trajectory SFT Trainer (Colab & SLURM Auto-Resume Ready).
Supports unified comparison across `--variant`:
  - `ours`: ELBO-rewritten thoughts + verified actions + detour step loss masking
  - `vanilla_teacher`: Raw teacher thoughts + actions (standard SFT baseline)
  - `srft_mask_only`: Raw teacher thoughts + actions + detour step loss masking
  - `action_only`: Verified actions without thoughts
"""
from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List

from agent_sft_align.data import annotate_detour_and_error_steps, load_eto_trajectories
from agent_sft_align.metrics.span_tokenizer import resolve_prompt_mode
from agent_sft_align.schema import AgentTrajectory
from agent_sft_align.training.sft_dataset import IGNORE_INDEX, SFTVariant, build_sft_features_for_trajectory


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Train Agent SFT Model with Unified Variants")
    p.add_argument("--model", type=str, default="Qwen/Qwen2.5-7B-Instruct")
    p.add_argument("--rewritten-jsonl", type=str, default=None, help="Path to JSONL output of run_rewrite_dataset.py")
    p.add_argument("--task", type=str, default="alfworld", choices=["alfworld", "webshop", "sciworld"])
    p.add_argument("--variant", type=str, default="ours", choices=["ours", "vanilla_teacher", "srft_mask_only", "action_only"])
    p.add_argument("--prompt-mode", type=str, default="auto", choices=["auto", "chat", "react_raw"])
    p.add_argument("--output-dir", type=str, default="checkpoints/alfworld_ours")
    p.add_argument("--max-seq-length", type=int, default=4096)
    p.add_argument("--epochs", type=float, default=3.0)
    p.add_argument("--lr", type=float, default=2e-5)
    p.add_argument("--per-device-batch-size", type=int, default=2)
    p.add_argument("--grad-accum", type=int, default=8)
    p.add_argument("--save-steps", type=int, default=200)
    p.add_argument("--use-lora", action="store_true")
    p.add_argument("--lora-r", type=int, default=64)
    p.add_argument("--seed", type=int, default=42)
    return p.parse_args()


def load_trajectories_for_training(args: argparse.Namespace) -> List[AgentTrajectory]:
    if args.rewritten_jsonl:
        trajs: List[AgentTrajectory] = []
        with open(args.rewritten_jsonl, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    trajs.append(AgentTrajectory.from_dict(json.loads(line)))
        return trajs

    if args.variant == "ours":
        raise ValueError("`--variant ours` requires `--rewritten-jsonl` generated by `run_rewrite_dataset.py`.")
    trajs = load_eto_trajectories(task=args.task)
    annotate_detour_and_error_steps(trajs)
    return trajs


@dataclass
class CausalSFTCollator:
    pad_token_id: int

    def __call__(self, features: List[Dict[str, List[int]]]) -> Dict[str, Any]:
        import torch

        max_len = max(len(f["input_ids"]) for f in features)
        input_ids, attention_mask, labels = [], [], []
        for f in features:
            pad_len = max_len - len(f["input_ids"])
            input_ids.append(f["input_ids"] + [self.pad_token_id] * pad_len)
            attention_mask.append(f["attention_mask"] + [0] * pad_len)
            labels.append(f["labels"] + [IGNORE_INDEX] * pad_len)
        return {
            "input_ids": torch.tensor(input_ids, dtype=torch.long),
            "attention_mask": torch.tensor(attention_mask, dtype=torch.long),
            "labels": torch.tensor(labels, dtype=torch.long),
        }


def main() -> None:
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer, Trainer, TrainingArguments
    from transformers.trainer_utils import get_last_checkpoint

    args = parse_args()
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    tokenizer = AutoTokenizer.from_pretrained(args.model, use_fast=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    prompt_mode = resolve_prompt_mode(tokenizer, args.prompt_mode, args.model)

    trajs = load_trajectories_for_training(args)
    variant: SFTVariant = args.variant  # type: ignore[assignment]
    encoded_dataset = [
        build_sft_features_for_trajectory(
            trajectory=t,
            tokenizer=tokenizer,
            variant=variant,
            prompt_mode=prompt_mode,
            max_seq_length=args.max_seq_length,
        )
        for t in trajs
    ]
    # Keep only examples with at least one supervised label
    encoded_dataset = [ex for ex in encoded_dataset if any(lbl != IGNORE_INDEX for lbl in ex["labels"])]
    print(f"Prepared {len(encoded_dataset)} tokenized trajectories for variant=`{args.variant}` (mode=`{prompt_mode}`).")

    use_bf16 = torch.cuda.is_available() and torch.cuda.is_bf16_supported()
    model = AutoModelForCausalLM.from_pretrained(
        args.model,
        torch_dtype=torch.bfloat16 if use_bf16 else torch.float16,
    )
    if args.use_lora:
        from peft import LoraConfig, get_peft_model

        peft_cfg = LoraConfig(
            r=args.lora_r,
            lora_alpha=args.lora_r * 2,
            lora_dropout=0.05,
            bias="none",
            task_type="CAUSAL_LM",
            target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
        )
        model = get_peft_model(model, peft_cfg)
        model.print_trainable_parameters()

    training_args = TrainingArguments(
        output_dir=str(out_dir),
        num_train_epochs=args.epochs,
        per_device_train_batch_size=args.per_device_batch_size,
        gradient_accumulation_steps=args.grad_accum,
        learning_rate=args.lr,
        lr_scheduler_type="cosine",
        warmup_ratio=0.05,
        bf16=use_bf16,
        fp16=(not use_bf16 and torch.cuda.is_available()),
        gradient_checkpointing=True,
        logging_steps=10,
        save_strategy="steps",
        save_steps=args.save_steps,
        save_total_limit=2,
        seed=args.seed,
        remove_unused_columns=False,
        report_to="none",
    )

    trainer = Trainer(
        model=model,
        args=training_args,
        train_dataset=encoded_dataset,
        data_collator=CausalSFTCollator(pad_token_id=tokenizer.pad_token_id),
    )

    last_ckpt = get_last_checkpoint(str(out_dir)) if out_dir.exists() else None
    if last_ckpt is not None:
        print(f"Resuming training from checkpoint: {last_ckpt}")
    trainer.train(resume_from_checkpoint=last_ckpt)

    final_dir = out_dir / "final"
    trainer.save_model(str(final_dir))
    tokenizer.save_pretrained(str(final_dir))
    print(f"Saved final checkpoint to {final_dir.resolve()}")


if __name__ == "__main__":
    main()
